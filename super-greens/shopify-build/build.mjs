function section(page, x, ssr) {
  const pseudoCss = ssr.pseudo.map((p) => `.${p.cls}${p.pseudo === 'before' || p.pseudo === 'after' ? '::' : ':'}${p.pseudo}{${p.css.split(/;(?![^(]*\))/).map((d) => d.trim()).filter(Boolean).map((d) => /!\s*important$/i.test(d) ? d : d + ' !important').join(';')}}`).join('\n');
  const scripts = x.scripts.map((s) => `<script src="${s}" defer></script>`).join('\n');
  const schema = { name: page.title, tag: 'section', class: 'lx-funnel-section', settings: SETTINGS(x) };
  return `{%- comment -%} ${page.title}: generated by shopify-build/build.mjs. Edit the design + rebuild, not this file. {%- endcomment -%}
{%- liquid
  assign lxa = 'lx-dc.js' | asset_url | split: 'lx-dc.js' | first
  assign p = section.settings.product
  if p == blank
    assign p = all_products['${PRODUCT}']
  endif
  assign v = p.selected_or_first_available_variant
  assign spid = section.settings.selling_plan_id | strip
  if spid == blank and p.selling_plan_groups.size > 0
    assign spid = p.selling_plan_groups.first.selling_plans.first.id
  endif
-%}
<style>
${liquidSafe(x.css)}
${pseudoCss}
</style>
<div id="lx-root" data-ssr>${liquidSafe(ssr.html)}</div>
<script>
  window.LX_ASSETS = {{ lxa | json }};
  window.LX_CFG = {
    funnel: ${JSON.stringify(page.template)},
    handle: {{ p.handle | default: '${PRODUCT}' | json }},
    variantId: {{ v.id | json }},
    price: {% if v %}{{ v.price | divided_by: 100.0 | json }}{% else %}null{% endif %},
    sellingPlanId: {% if spid != blank %}{{ spid | json }}{% else %}null{% endif %},
    afterAdd: {{ section.settings.after_add | json }},
    klaviyoCompanyId: {{ section.settings.klaviyo_company_id | strip | json }},
    klaviyoListId: {{ section.settings.klaviyo_list_id | strip | json }}
  };
  window.LX_PROPS = {
    defaultPlan: {{ section.settings.default_plan | json }},
    cadence: {{ section.settings.cadence | json }},
    ctaLabel: {{ section.settings.cta_label | json }},
    disc2: {{ section.settings.disc2 | default: 0 | json }},
    disc3: {{ section.settings.disc3 | default: 0 | json }},
    disc4: {{ section.settings.disc4 | default: 0 | json }},
    disc5: {{ section.settings.disc5 | default: 0 | json }},
    disc6: {{ section.settings.disc6 | default: 0 | json }},
    tshirtValue: {{ section.settings.tshirt_value | strip | json }},
    hatValue: {{ section.settings.hat_value | strip | json }}
  };
</script>
${scripts}
<script src="{{ 'lx-funnel.js' | asset_url }}" defer></script>
<script src="{{ 'lx-dc.js' | asset_url }}" defer></script>
<script src="{{ '${page.key}.js' | asset_url }}" defer></script>
<script>
  window.addEventListener('DOMContentLoaded', function () {
    window.LXDC.mount(${JSON.stringify(page.key)}, document.getElementById('lx-root'), window.LX_PROPS);
  });
</script>

{% schema %}
${JSON.stringify(schema, null, 2)}
{% endschema %}
`;
}

function template(page) {
  return JSON.stringify({
    layout: 'lx-funnel',
    sections: { main: { type: page.key, settings: { product: PRODUCT } } },
    order: ['main'],
  }, null, 2) + '\n';
}

function images() {
  const dir = path.join(SRC, 'assets');
  const list = fs.readdirSync(dir).filter((f) => !f.startsWith('._'));
  for (const f of list) {
    const src = path.join(dir, f);
    if (/\.png$/.test(f)) {
      const out = path.join(OUT, 'assets', 'lx-sg-' + f.replace(/\.png$/, '.webp'));
      if (fs.existsSync(out) && fs.statSync(out).mtimeMs > fs.statSync(src).mtimeMs) continue;
      const tmp = path.join(HERE, '.tmp-' + f);
      execFileSync('sips', ['-Z', '1800', src, '--out', tmp], { stdio: 'ignore' });
      execFileSync('cwebp', ['-quiet', '-q', '80', '-alpha_q', '90', '-m', '6', tmp, '-o', out]);
      fs.unlinkSync(tmp);
    } else if (/\.(svg|ttf)$/.test(f)) fs.copyFileSync(src, path.join(OUT, 'assets', 'lx-sg-' + f));
  }
  for (const f of fs.readdirSync(path.join(dir, 'fonts')).filter((f) => /^Poppins.*\.woff2$/.test(f))) {
    fs.copyFileSync(path.join(dir, 'fonts', f), path.join(OUT, 'assets', 'lx-sg-' + f));
  }
}

for (const d of ['assets', 'layout', 'sections', 'templates']) fs.mkdirSync(path.join(OUT, d), { recursive: true });
if (!process.argv.includes('--no-img')) images();
for (const page of PAGES) {
  const x = extract(page);
  const js = pageJs(page, x);
  fs.writeFileSync(path.join(OUT, 'assets', page.key + '.js'), js);
  const ssr = prerender(page, js);
  const sec = section(page, x, ssr);
  fs.writeFileSync(path.join(OUT, 'sections', page.key + '.liquid'), sec);
  fs.writeFileSync(path.join(OUT, 'templates', 'page.' + page.template + '.json'), template(page));
  console.log(page.key, 'js', (js.length / 1024).toFixed(0) + 'KB', 'section', (sec.length / 1024).toFixed(0) + 'KB');
}

// Local preview (no Shopify): ../preview/<page>.html served from the super-greens folder
fs.mkdirSync(path.join(HERE, '../preview'), { recursive: true });
for (const page of PAGES) {
  let s = fs.readFileSync(path.join(OUT, 'sections', page.key + '.liquid'), 'utf8');
  s = s.replace(/\{%- comment -%\}[\s\S]*?\{%- endcomment -%\}/, '').replace(/\{%- liquid[\s\S]*?-%\}/, '').replace(/\{% schema %\}[\s\S]*$/, '');
  s = s.replace(/<script>\s*window\.LX_ASSETS[\s\S]*?<\/script>/, `<script>window.LX_ASSETS='../shopify-theme/assets/';window.LX_CFG={funnel:'${page.template}',handle:'${PRODUCT}',variantId:null,price:49.95,sellingPlanId:null};window.LX_PROPS={};</script>`);
  s = s.replace(/\{\{ '([^']+)' \| asset_url \}\}/g, '../shopify-theme/assets/$1').replace(/\{\{ "(\{\{|\{%)" \}\}/g, '$1');
  if (/\{\{|\{%/.test(s)) console.warn('preview: leftover liquid in', page.key);
  fs.writeFileSync(path.join(HERE, '../preview', page.template + '.html'), `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${page.title}</title></head><body>${s}</body></html>`);
}

// Drop converted assets that neither page references (keeps the theme lean)
{
  const used = PAGES.map((p) => fs.readFileSync(path.join(OUT, 'assets', p.key + '.js'), 'utf8') + fs.readFileSync(path.join(OUT, 'sections', p.key + '.liquid'), 'utf8')).join('') + fs.readFileSync(path.join(OUT, 'layout/lx-funnel.liquid'), 'utf8');
  for (const f of fs.readdirSync(path.join(OUT, 'assets'))) {
    if (!f.startsWith('lx-sg-') || PAGES.some((p) => f === p.key + '.js')) continue;
    const stem = f.slice(6).replace(/\.[^.]+$/, '');
    if (!used.includes(f) && !used.includes(`'${stem}'`)) fs.unlinkSync(path.join(OUT, 'assets', f));
  }
  for (const f of fs.readdirSync(path.join(OUT, 'assets'))) if (f.startsWith('._')) fs.unlinkSync(path.join(OUT, 'assets', f));
}
