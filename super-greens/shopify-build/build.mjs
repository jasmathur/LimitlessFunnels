const decode = (s) => s.replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

// assets/foo.png -> __LXA__foo.webp ; assets/fonts/x.woff2 -> __LXA__x.woff2
function rewriteAssets(s) {
  return s
    .replace(/(?:\.\/)?assets\/(?:fonts\/)?([\w-]+)\.png/g, '__LXA__lx-sg-$1.webp')
    .replace(/(?:\.\/)?assets\/(?:fonts\/)?([\w.-]+\.(?:svg|ttf|woff2|jpg|jpeg|webp))/g, '__LXA__lx-sg-$1');
}
function rewriteLinks(s) {
  return s
    .replace(/\.\.\/\.\.\/pages\/privacy-policy\/index\.html/g, '/policies/privacy-policy')
    .replace(/\.\.\/\.\.\/pages\/terms-conditions\/index\.html/g, '/policies/terms-of-service')
    .replace(/\.\.\/\.\.\/pages\/returns-exchanges\/index\.html/g, '/pages/returns-exchanges')
    .replace(/https:\/\/www\.limitlessx\.com\/policies\//g, '/policies/');
}
function mustReplace(s, from, to, label) {
  const n = s.split(from).length - 1;
  if (!n) throw new Error('Patch not found: ' + label);
  return s.split(from).join(to);
}
function patchLogic(js) {
  js = js.replace(/'assets\/' \+ ([\w.]+) \+ '\.png'/g, "LXA + 'lx-sg-' + $1 + '.webp'");
  js = rewriteAssets(js);
  js = js.replace(/'__LXA__/g, "LXA + '");
  if (js.includes('__LXA__')) throw new Error('Unhandled asset ref in logic');
  // Prototype cart hand-off -> real Shopify cart (handled by lx-funnel.js)
  js = js.replace(/'Post-Purchase Flow\.dc\.html\?plan=' \+ (\w+) \+ '&qty=' \+ (\w+) \+ '#cart'/g, "'#lx-cart-' + $1 + '-' + $2");
  if (js.includes('Post-Purchase')) throw new Error('Unhandled cart link in logic');
  // Real product price from Shopify
  js = mustReplace(js, 'PRICE = 49.95;', 'PRICE = (window.LX_CFG && +window.LX_CFG.price) || 49.95;', 'price');
  // Lead capture
  js = mustReplace(js, "this.track('EmailCaptured', { sms_optin: s.sms });",
    "this.track('EmailCaptured', { sms_optin: s.sms }); if (window.LX) window.LX.lead(s.email, s.phone, s.sms, s.answers);", 'lead');
  return rewriteLinks(js);
}

function extract(page) {
  const raw = fs.readFileSync(path.join(SRC, page.file), 'utf8');
  const open = raw.indexOf('<x-dc>'), close = raw.lastIndexOf('</x-dc>');
  let tpl = raw.slice(open + 6, close);
  const hm = tpl.match(/<helmet>([\s\S]*?)<\/helmet>/);
  const helmet = hm ? hm[1] : '';
  tpl = tpl.replace(/<helmet>[\s\S]*?<\/helmet>/, '');
  const sm = raw.match(/<script type="text\/x-dc" data-dc-script data-props="([^"]*)">([\s\S]*?)<\/script>/);
  const propDefs = JSON.parse(decode(sm[1]));
  const props = {};
  for (const [k, v] of Object.entries(propDefs)) if (k[0] !== '$' && 'default' in v) props[k] = v.default;
  const css = [...helmet.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join('\n');
  const scripts = [...helmet.matchAll(/<script src="([^"]+)"><\/script>/g)].map((m) => m[1]);
  return { tpl: rewriteLinks(rewriteAssets(tpl)), logic: patchLogic(sm[2]), props, css: rewriteAssets(css), scripts };
}

// __LXA__name -> Liquid asset_url ; also neutralise any stray Liquid delimiters
function liquidSafe(s) {
  return s.replace(/\{\{/g, '{{ "{{" }}').replace(/\{%/g, '{{ "{%" }}')
    .replace(/__LXA__([\w.-]+)/g, (_, f) => `{{ '${f}' | asset_url }}`);
}

function pageJs(page, x) {
  return `/* ${page.title}: generated by shopify-build/build.mjs from the Claude Design file. Do not edit by hand. */
(function () {
  var A = window.LX_ASSETS || '__LXA__';
  window.LXDC.register(${JSON.stringify(page.key)}, {
    tpl: ${JSON.stringify(x.tpl)}.replace(/__LXA__/g, A),
    props: ${JSON.stringify(x.props)},
    logic: function (DCLogic) {
      var StreamableLogic = DCLogic, LXA = A;
${x.logic}
      return Component;
    }
  });
})();
`;
}

function prerender(page, js) {
  const dom = new JSDOM('<!doctype html><html><head></head><body></body></html>', { runScripts: 'outside-only', pretendToBeVisual: true });
  const w = dom.window;
  w.matchMedia = () => ({ matches: false, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} });
  w.eval(fs.readFileSync(path.join(OUT, 'assets/lx-dc.js'), 'utf8'));
  w.eval(js);
  const html = w.LXDC.renderHTML(page.key, w.document);
  return { html, pseudo: w.LXDC.pseudoCss };
}

